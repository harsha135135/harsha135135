def _glyph(ch: str) -> tuple[str, ...]:
    return GLYPHS.get(ch, GLYPHS[" "])


def text_width(text: str, scale: int = 1, tracking: int = 1) -> int:
    if not text:
        return 0
    return (sum(len(_glyph(ch)[0]) + tracking for ch in text.upper()) - tracking) * scale


def draw_text(draw, x: int, y: int, text: str, fill, scale: int = 1, tracking: int = 1) -> None:
    """Draw ``text`` with its top-left at (x, y) on a PIL ImageDraw."""
    for ch in text.upper():
        glyph = _glyph(ch)
        for gy, row in enumerate(glyph):
            for gx, bit in enumerate(row):
                if bit == "#":
                    px, py = x + gx * scale, y + gy * scale
                    draw.rectangle((px, py, px + scale - 1, py + scale - 1), fill=fill)
        x += (len(glyph[0]) + tracking) * scale
